# hand-written completions: what they offer

def existing(prog: str) -> dict[str, Path]:
    found = {}
    for shell, names in {"bash": [f"bash/{prog}.bash", f"{prog}.bash", f"bash/{prog}"],
                         "zsh": [f"zsh/_{prog}", f"_{prog}"],
                         "fish": [f"fish/{prog}.fish", f"{prog}.fish"]}.items():
        for n in names:
            p = ROOT / "completions" / n
            if p.exists():
                found[shell] = p
                break
    return found


def target(prog: str, shell: str) -> Path:
    nested = (ROOT / "completions" / "bash").is_dir() or (ROOT / "completions" / "fish").is_dir()
    name = {"bash": f"{prog}.bash", "zsh": f"_{prog}", "fish": f"{prog}.fish"}[shell]
    return ROOT / "completions" / (f"{shell}/{name}" if nested else name)


def offered_bash(text: str, subs: set[str]) -> tuple[set[str], dict[str, set[str]]]:
    m = re.search(r'subcommands="([^"]*)"', text)
    listed = set(m.group(1).split()) if m else set()
    per: dict[str, set[str]] = {}
    lines = text.split("\n")
    for i, ln in enumerate(lines):
        a = re.match(r"^\s*([\w|*-]+)\)\s*(.*)$", ln)
        if not a:
            continue
        names = a.group(1).split("|")
        if not all(n in subs or n == "*" for n in names):
            continue
        body, j = a.group(2), i
        while ";;" not in body and j + 1 < len(lines):
            j += 1
            body += "\n" + lines[j]
        words = set()
        for q in re.findall(r'(?:compgen -W|opts=)\s*"([^"]*)"', body):
            words |= {w for w in q.split() if w.startswith("-")}
        for n in names:
            per.setdefault(n, set()).update(words)
    return listed, per


def offered_fish(text: str, prog: str) -> tuple[set[str], dict[str, set[str]], set[str]]:
    listed: set[str] = set()
    per: dict[str, set[str]] = {}
    glob: set[str] = set()
    for ln in text.split("\n"):
        if not re.match(r"^\s*complete\s+-c\s+%s\b" % re.escape(prog), ln):
            continue
        try:
            toks = shlex.split(ln, comments=True)
        except ValueError:
            continue
        cond, args, opts = "", [], set()
        i = 0
        while i < len(toks):
            t = toks[i]
            nxt = toks[i + 1] if i + 1 < len(toks) else ""
            if t in ("-n", "--condition"):
                cond, i = nxt, i + 2
                continue
            if t in ("-a", "-xa", "--arguments", "-fa", "-ra"):
                args += nxt.split()
                i += 2
                continue
            if t in ("-l", "--long-option"):
                opts.add("--" + nxt); i += 2; continue
            if t in ("-s", "--short-option"):
                opts.add("-" + nxt); i += 2; continue
            if t in ("-o", "--old-option"):
                opts.add("-" + nxt); i += 2; continue
            if t in ("-d", "--description", "-c", "--command"):
                i += 2
                continue
            i += 1
        args = [] if any("(" in a for a in args) else args
        opts |= {a for a in args if a.startswith("-")}
        m = re.search(r"__fish_seen_subcommand_from\s+(.*)$", cond)
        if m and not cond.startswith("not "):
            for s in m.group(1).split():
                per.setdefault(s, set()).update(opts)
        elif not cond or "__fish_use_subcommand" in cond or cond.startswith("not __fish_seen"):
            listed |= {a for a in args if not a.startswith("-") and "(" not in a}
            glob |= opts
    return listed, per, glob


def mismatches(tool: Tool) -> list[str]:
    out: list[str] = []
    subs = {c.name for c in tool.commands}
    globals_ = {n for o in tool.global_opts for n in o.names}
    # help text against the code
    for o in tool.global_help():
        if not set(o.names) & globals_:
            out.append(f"help: lists {'/'.join(o.names)} as a global option; the dispatcher "
                       f"does not parse it before the command")
    for c in tool.commands:
        acc = tool.accepted(c)
        for o in tool.help_opts(c):
            if not set(o.names) & acc:
                out.append(f"help: {c.name}: documents {'/'.join(o.names)}, which its own code does not parse")
    for shell, path in existing(tool.prog).items():
        text = path.read_text(encoding="utf-8")
        if NOTE in text:
            continue
        rel = path.relative_to(ROOT)
        if shell == "bash":
            listed, per = offered_bash(text, subs | {"*"})
            glob: set[str] = set()
        elif shell == "fish":
            listed, per, glob = offered_fish(text, tool.prog)
        else:
            continue
        for s in sorted(subs - listed):
            out.append(f"{rel}: does not offer subcommand {s}")
        for s in sorted(listed - subs):
            out.append(f"{rel}: offers subcommand {s}, which has no module")
        for o in sorted(glob - globals_):
            out.append(f"{rel}: offers global {o}, which the dispatcher does not parse")
        default = per.get("*", set())
        for c in tool.commands:
            got = per.get(c.name, default if shell == "bash" else set())
            acc = tool.accepted(c)
            bad = sorted(got - acc)
            if bad:
                out.append(f"{rel}: {c.name}: offers {' '.join(bad)}, which its own code does not parse")
            miss = sorted({n for o in c.opts for n in o.names if n.startswith("--")} - got - globals_)
            if miss:
                out.append(f"{rel}: {c.name}: does not offer {' '.join(miss)}, which the code parses")
    return out


# ---------------------------------------------------------------------------

def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def options_table(tool: Tool) -> list[str]:
    """One line per subcommand: NAME<TAB>OPT:kind OPT:kind ..., every
    spelling of every option it parses, -h and --help left out."""
    out = []
    for c in tool.commands:
        spell = [f"{n}:{'value' if o.value else 'flag'}"
                 for o in c.opts for n in o.names if n not in ("-h", "--help")]
        out.append(f"{c.name}\t{' '.join(dict.fromkeys(spell))}")
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    if "--options" in argv:
        for prog in [a for a in argv if a != "--options"] or PROGS:
            print("\n".join(options_table(Tool(prog))))
        return 0
    progs = [a for a in argv if a != "--check"] or PROGS
    for prog in progs:
        tool = Tool(prog)
        for m in mismatches(tool):
            print(f"{prog}: {m}")
        if check:
            continue
        write(ROOT / "man" / f"{prog}.1", man_page(tool))
        have = existing(prog)
        for shell, gen in (("bash", bash), ("zsh", zsh), ("fish", fish)):
            path = have.get(shell)
            if path is None or NOTE in path.read_text(encoding="utf-8"):
                write(path or target(prog, shell), gen(tool))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
