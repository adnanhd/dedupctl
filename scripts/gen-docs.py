# completion scripts

def comp_opts(tool: Tool, c: Command) -> list[Opt]:
    """What a completion offers after C: the options the code parses,
    with the help text's words for them."""
    helped = {n: o for o in tool.help_opts(c) + tool.global_help() for n in o.names}
    out = []
    for o in c.opts:
        h = next((helped[n] for n in o.names if n in helped), None)
        out.append(Opt(o.names, o.value or bool(h and h.value), o.eq, (h.metavar if h else ""),
                       (h.desc if h else "")))
    return out


def positional_glob(tool: Tool) -> tuple[str, str, str] | None:
    """For a tool with no subcommands whose first argument names a file
    (CONFIG="$HOME/.config/x/${PROFILE}.conf"), the directory and suffix."""
    m = re.search(r'^(\w+)="\$\{1:\?', tool.main, re.M)
    if not m:
        return None
    var = m.group(1)
    p = re.search(r'^\w+="\$\{?HOME\}?/([^"$]*)/\$\{%s\}([^"/$]*)"' % var, tool.main, re.M)
    return (p.group(1), p.group(2), var.lower()) if p else None


def zsh_q(s: str) -> str:
    return s.replace("'", "'\\''")


def zsh_spec(o: Opt) -> str:
    desc = zsh_q(o.desc or "").replace("[", "\\[").replace("]", "\\]")
    val = (":" + zsh_q(o.metavar or "value").replace(":", "\\:") + ":") if o.value else ""
    eq = "=" if o.eq and o.value else ""
    if len(o.names) == 1:
        return f"'{o.names[0]}{eq}[{desc}]{val}'"
    excl = " ".join(o.names)
    return f"'({excl})'{{{','.join(o.names)}}}'{eq}[{desc}]{val}'"


def zsh(tool: Tool) -> str:
    fn = f"_{tool.prog}"
    out = [f"#compdef {tool.prog}", f"# {NOTE}", "", f"{fn}() {{"]
    gl = " \\\n    ".join(zsh_spec(o) for o in tool.global_opts)
    if tool.commands:
        out += ["  local curcontext=\"$curcontext\" state line", "  local -a commands", "  commands=("]
        out += [f"    '{c.name}:{zsh_q(c.summary)}'" for c in tool.commands]
        out += ["  )", "  _arguments -C \\"]
        if gl:
            out.append(f"    {gl} \\")
        out += ["    '1: :->command' \\", "    '*:: :->args' && return", "  case $state in",
                f"    command) _describe -t commands '{tool.prog} command' commands ;;",
                "    args)", "      case $words[1] in"]
        for c in tool.commands:
            specs = " \\\n            ".join([zsh_spec(o) for o in comp_opts(tool, c)] + ["'*: :_files'"])
            out.append(f"        ({c.name}) _arguments \\\n            {specs} ;;")
        out += ["        (*) _files ;;", "      esac ;;", "  esac"]
    else:
        pg = positional_glob(tool)
        first = (f"'1:{zsh_q(pg[2])}:{{local -a v; v=(~/{pg[0]}/*{pg[1]}(N:t:r)); "
                 f"compadd -a v}}'") if pg else "'1: :_files'"
        out += ["  _arguments \\"] + ([f"    {gl} \\"] if gl else []) + [f"    {first}"]
    out += ["}", "", f'{fn} "$@"', ""]
    return "\n".join(out)


def bash(tool: Tool) -> str:
    fn = "_" + re.sub(r"\W", "_", tool.prog)
    gl = " ".join(n for o in tool.global_opts for n in o.names)
    out = ["# bash completion for " + tool.prog, f"# {NOTE}", "", f"{fn}() {{",
           '    local cur=${COMP_WORDS[COMP_CWORD]}', "    COMPREPLY=()"]
    if tool.commands:
        out += ['    local i cmd=""', "    for ((i = 1; i < COMP_CWORD; i++)); do",
                '        [[ ${COMP_WORDS[i]} != -* ]] && { cmd=${COMP_WORDS[i]}; break; }', "    done",
                '    if [[ -z $cmd ]]; then',
                f'        COMPREPLY=($(compgen -W "{" ".join(c.name for c in tool.commands)} {gl}" -- "$cur"))',
                "        return", "    fi", '    case $cmd in']
        for c in tool.commands:
            ws = " ".join(n for o in comp_opts(tool, c) for n in o.names)
            out.append(f'        {c.name}) COMPREPLY=($(compgen -W "{ws} {gl}" -- "$cur")) ;;')
        out.append("    esac")
    else:
        pg = positional_glob(tool)
        if pg:
            out += ['    if [[ $COMP_CWORD -eq 1 ]]; then', "        local f v=()",
                    f'        for f in "$HOME/{pg[0]}"/*{pg[1]}; do [[ -e $f ]] && v+=("$(basename "$f" {pg[1]})"); done',
                    f'        COMPREPLY=($(compgen -W "${{v[*]}} {gl}" -- "$cur"))', "    fi"]
        elif gl:
            out.append(f'    [[ $COMP_CWORD -eq 1 ]] && COMPREPLY=($(compgen -W "{gl}" -- "$cur"))')
    out += ["}", "", f"complete {'-o default ' if tool.commands else ''}-F {fn} {tool.prog}", ""]
    return "\n".join(out)


def fish_q(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def fish_opt(prog: str, o: Opt, cond: str) -> str:
    parts = [f"complete -c {prog}"] + ([f"-n {fish_q(cond)}"] if cond else [])
    for n in o.names:
        parts.append(f"-l {n[2:]}" if n.startswith("--") else
                     (f"-s {n[1:]}" if len(n) == 2 else f"-o {n[1:]}"))
    if o.value:
        parts.append("-r")
    if o.desc:
        parts.append(f"-d {fish_q(o.desc)}")
    return " ".join(parts)


def fish(tool: Tool) -> str:
    out = [f"# fish completion for {tool.prog}", f"# {NOTE}", ""]
    if tool.commands:
        names = " ".join(c.name for c in tool.commands)
        out.append(f"complete -c {tool.prog} -f")
        out += [f"complete -c {tool.prog} -n {fish_q('not __fish_seen_subcommand_from ' + names)} "
                f"-a {c.name} -d {fish_q(c.summary)}" for c in tool.commands]
        out += [fish_opt(tool.prog, o, "") for o in tool.global_opts]
        for c in tool.commands:
            out += [fish_opt(tool.prog, o, f"__fish_seen_subcommand_from {c.name}")
                    for o in comp_opts(tool, c)]
    else:
        pg = positional_glob(tool)
        out += [fish_opt(tool.prog, o, "") for o in tool.global_opts]
        if pg:
            out.append(f"complete -c {tool.prog} -f -n {fish_q('__fish_is_nth_token 1')} -a "
                       f"{fish_q(f'(for f in ~/{pg[0]}/*{pg[1]}; basename $f {pg[1]}; end)')}")
    return "\n".join(out) + "\n"


