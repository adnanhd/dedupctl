# reading help text

@dataclass
class Entry:
    tag: str
    desc: str
    sub: list["Entry"] = field(default_factory=list)


def sections(text: str) -> tuple[list[str], list[tuple[str, list[str]]]]:
    """(lines before the first section, [(header, lines)]).  A section
    header is an unindented line ending in a colon."""
    pre: list[str] = []
    out: list[tuple[str, list[str]]] = []
    for ln in text.split("\n"):
        inline = re.match(r"^(Usage):\s+(\S.*)$", ln, re.I)
        if inline:
            out.append((inline.group(1), [" " * inline.start(2) + inline.group(2)]))
        elif re.match(r"^\S[^:]*:\s*$", ln):
            out.append((ln.strip()[:-1].strip(), []))
        elif out:
            out[-1][1].append(ln)
        else:
            pre.append(ln)
    return pre, out


def indent(ln: str) -> int:
    return len(ln) - len(ln.lstrip(" "))


def split2(s: str) -> tuple[str, str]:
    """`tag   description' or `tag : description'."""
    m = re.match(r"^(.*?\S)(?:\s+:\s+|\s{2,})(\S.*)$", s)
    return (m.group(1), m.group(2)) if m else (s, "")


def split_list(lines: list[str]) -> tuple[list[str], list[str]]:
    """A section's two-column list, and the text after it: the list ends
    at the first line indented less than its first line."""
    body = [ln.rstrip() for ln in lines]
    first = next((i for i, ln in enumerate(body) if ln.strip()), None)
    if first is None:
        return [], []
    base = indent(body[first])
    for i in range(first, len(body)):
        if body[i].strip() and indent(body[i]) < base:
            return body[first:i], body[i:]
    return body[first:], []


def paragraphs(lines: list[str]) -> list[str]:
    out, cur = [], []
    for ln in lines + [""]:
        if ln.strip():
            cur.append(ln.strip())
        elif cur:
            out.append(" ".join(cur))
            cur = []
    return out


def entries(lines: list[str], usage: bool = False) -> list[Entry]:
    body = [ln for ln in split_list(lines)[0] if ln.strip()]
    if not body:
        return []
    base = indent(body[0])
    out: list[Entry] = []
    for ln in body:
        if indent(ln) == base or not out:
            tag, desc = split2(ln.strip())
            if usage and re.match(r"^(\[|<|-|[A-Z_]{3,}\b)", desc):
                tag, desc = " ".join(ln.split()), ""
            out.append(Entry(tag, desc))
        else:
            tag, desc = split2(ln.strip())
            last = out[-1]
            if desc and (last.sub or re.match(r"^[\w(-][\w()=,/ |.-]*$", tag) and len(tag) < 24
                         and last.desc.rstrip().endswith(":")):
                last.sub.append(Entry(tag, desc))
            elif last.sub:
                last.sub[-1].desc += " " + ln.strip()
            else:
                last.desc = (last.desc + " " + ln.strip()).strip()
    return out


def tag_names(tag: str) -> list[str]:
    return re.findall(r"(?<![\w-])(%s)" % OPT, tag)


def tag_metavar(tag: str) -> str:
    m = re.search(r"(?:%s)(?:=|\s+)\"?([<A-Z][^\s,\]\"]*)" % OPT, tag)
    return m.group(1) if m else ""


def entry_opts(e: Entry) -> list[Opt]:
    """The options a help entry describes.  `-n, --node NODE' is one
    option spelled two ways; `--start/--end DT' and `--timeout|--running'
    are several sharing a description; `--eff --visual' is a combination
    and describes neither on its own."""
    if not e.tag.lstrip().startswith("-") or not tag_names(e.tag):
        return []
    if re.search(r"(?<![\w-])%s(?:\s+)%s" % (OPT, OPT), e.tag):
        return []
    mv = tag_metavar(e.tag)
    desc = (e.desc + "".join(f" {s.tag}: {s.desc}" for s in e.sub)).strip()
    out = []
    for part in re.split(r"[|/]", e.tag):
        names = tag_names(part)
        if names:
            out.append(Opt(names, bool(mv), "=" in e.tag, mv, desc))
    return out


