# troff

HOME = str(Path.home())


def esc(text: str) -> str:
    text = text.replace(HOME, "~").replace("\\", "\\e").replace("-", "\\-")
    text = re.sub(r"`([^`'\n]+)'", r"\\(oq\1\\(cq", text)
    text = re.sub(r"(^|\s)(?=\S*_)", r"\1\\%", text)
    return text


def line(text: str) -> str:
    return "\n".join("\\&" + ln if ln[:1] in (".", "'") else ln for ln in text.split("\n"))


def bold_opts(text: str) -> str:
    """Escape TEXT and set every option in it bold."""
    parts = re.split(r"((?<![\w-])%s)" % OPT, text)
    return "".join(f"\\fB{esc(p)}\\fR" if i % 2 else esc(p) for i, p in enumerate(parts))


def sentence(text: str) -> str:
    text = " ".join(text.split())
    if text and text[0].islower():
        text = text[0].upper() + text[1:]
    return text if not text or text[-1] in ".!?:)" else text + "."


def tp(tag: str, desc: str) -> list[str]:
    return [".TP", line(tag), line(esc(sentence(desc)))] if desc else [".TP", line(tag)]


def usage_tag(prog: str, s: str) -> str:
    m = re.match(r"^(%s(?:\s+[\w-]+)?)(.*)$" % re.escape(prog), s)
    if m:
        return f"\\fB{esc(m.group(1))}\\fR{bold_opts(m.group(2))}"
    return bold_opts(s)


def render_entries(es: list[Entry], prog: str, usage: bool = False) -> list[str]:
    out: list[str] = []
    for e in es:
        tag = usage_tag(prog, e.tag) if usage else bold_opts(e.tag)
        out += tp(tag, e.desc)
        if e.sub:
            out.append(".RS")
            for s in e.sub:
                out += tp(bold_opts(s.tag), s.desc)
            out.append(".RE")
    return out


def nofill(lines: list[str]) -> list[str]:
    body = [ln.rstrip() for ln in lines]
    while body and not body[0].strip():
        body.pop(0)
    while body and not body[-1].strip():
        body.pop()
    if not body:
        return []
    base = min(indent(ln) for ln in body if ln.strip())
    return [".PP", ".RS", ".nf"] + [line(esc(ln[base:])) for ln in body] + [".fi", ".RE"]


def synopsis(tool: Tool) -> str:
    items = []
    for o in tool.global_opts:
        long = next((n for n in o.names if n.startswith("--")), o.names[0])
        short = next((n for n in o.names if not n.startswith("--")), None)
        name = short or long
        mv = f"\\~\\fI{esc(o.metavar or 'VALUE')}\\fR" if o.value else ""
        items.append(f"[\\fB{esc(name)}\\fR{mv}]")
    if tool.commands:
        items.append("\\fICOMMAND\\fR [\\fIARG\\fR\\~.\\|.\\|.]")
    else:
        m = re.search(r'\$\{1:\?\s*usage:\s*%s\s+([^}]*?)(?:\s{2,}|\(|\})' % re.escape(tool.prog),
                      tool.main, re.I)
        if m:
            items += [f"\\fI{esc(w.strip('<>'))}\\fR" for w in m.group(1).split()]
    return "\n".join([f".SY {esc(tool.prog)}", *items, ".YS"])


def opt_lines(opts: list[Opt]) -> list[str]:
    out = []
    for o in opts:
        tag = ", ".join(f"\\fB{esc(n)}\\fR" for n in o.names)
        if o.value:
            tag += ("=" if o.eq else "\\~") + f"\\fI{esc(o.metavar or 'VALUE')}\\fR"
        desc = o.desc or ("Print the help text and exit." if set(o.names) <= {"-h", "--help"}
                          else "Not described in the help text.")
        out += tp(tag, desc)
    return out


def render_body(lines: list[str], prog: str, documented: set[str]) -> list[str]:
    """Text and option runs, in their order: `-x  desc' lines (with any
    deeper lines under them) become a list, other lines paragraphs."""
    out: list[str] = []
    block: list[str] = []
    para: list[str] = []
    for ln in [x for x in lines if x.strip()] + ["\0"]:
        s = ln.strip()
        if block and s != "\0" and indent(ln) > indent(block[0]) :
            block.append(ln)
            continue
        if block:
            es = entries(block)
            documented |= {n for e in es for n in tag_names(e.tag)}
            out += render_entries(es, prog)
            block = []
        if s == "\0":
            break
        if s.startswith("-"):
            if para:
                out += [".PP", line(esc(" ".join(para)))]
                para = []
            block = [ln]
        else:
            para.append(s)
    if para:
        out += [".PP", line(esc(" ".join(para)))]
    return out


def command_page(tool: Tool, c: Command, prose: dict[str, str]) -> list[str]:
    out = [f'.SS "{esc(c.name)}"']
    documented: set[str] = set()

    def summary() -> list[str]:
        return [".PP", line(esc(sentence(c.summary)))] if c.summary else []
    if c.help:
        pre, secs = sections(c.help)
        title = next((ln for ln in pre if ln.strip()), "")
        rest_pre = paragraphs(pre[pre.index(title) + 1:] if title else pre)
        usage = [hs for hs in secs if hs[0].lower().startswith("usage")]
        for _, lines in usage:
            out += render_entries(entries(lines, usage=True), tool.prog, usage=True)
        out += summary()
        for para in rest_pre:
            out += [".PP", line(esc(para))]
        for _, lines in usage:
            for para in paragraphs(split_list(lines)[1]):
                out += [".PP", line(esc(para))]
        for head, lines in secs:
            low = head.lower()
            if low.startswith("usage"):
                continue
            if low.startswith("option"):
                es = entries(lines)
                documented |= {n for e in es for n in tag_names(e.tag)}
                out += [".PP", "Options:"] + render_entries(es, tool.prog)
                for para in paragraphs(split_list(lines)[1]):
                    out += [".PP", line(esc(para))]
            elif low.startswith("example"):
                body = [ln for ln in lines if ln.strip()]
                base = min((indent(ln) for ln in body), default=0)
                out += [".PP", "Examples:", ".PP", ".RS", ".EX"] + \
                       [line(esc(ln[base:])) for ln in body] + [".EE", ".RE"]
            else:
                out += [".PP", line(esc(head)) + ":"] + nofill(lines)
    elif c.overview:
        e = entries([c.overview[0]], usage=True)[0]
        out += tp(usage_tag(tool.prog, f"{tool.prog} {e.tag}"), "")
        if c.alias:
            out += summary()
        else:
            out += render_body(c.overview[1:], tool.prog, documented)
    else:
        out += summary()
    if c.name in prose:
        out.append(prose.pop(c.name).rstrip("\n"))
    if c.alias:
        return out
    # what the code parses that the help text never mentions
    globals_ = {n for o in tool.global_opts for n in o.names}
    extra = [o for o in c.opts if not set(o.names) & (documented | globals_)]
    if extra:
        common = {n: o for o in tool.global_help() for n in o.names}
        for o in extra:
            h = next((common[n] for n in o.names if n in common), None)
            if h is not None:
                o.desc, o.metavar = o.desc or h.desc, o.metavar or h.metavar
        out += [".PP", "Also parsed:" if documented else "Options:"] + opt_lines(extra)
    return out


def take_prose(template: str) -> tuple[str, dict[str, str]]:
    prose: dict[str, str] = {}

    def grab(m: re.Match[str]) -> str:
        prose[m.group(1).strip()] = m.group(2)
        return ""
    rest = re.sub(r'^\.\\" @prose ([^\n]+)\n(.*?)^\.\\" @end\n', grab, template, flags=re.M | re.S)
    return rest, prose


def man_page(tool: Tool) -> str:
    tpl_path = ROOT / "man" / f"{tool.prog}.1.in"
    template, prose = take_prose(tpl_path.read_text(encoding="utf-8"))
    parts = {
        "synopsis": synopsis(tool),
        "options": "\n".join(opt_lines(tool.global_opts)),
        "commands": "\n".join(ln for c in tool.commands for ln in command_page(tool, c, prose)),
    }
    if prose:
        raise SystemExit(f"gen-docs: {tool.prog}: @prose for unknown command(s): {', '.join(prose)}")
    page = re.sub(r'^\.\\" @generated (\w+)$', lambda m: parts[m.group(1)], template, flags=re.M)
    return (f'.\\" {NOTE.replace("source", "source and " + tpl_path.name)}\n' + page)


