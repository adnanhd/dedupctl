#!/usr/bin/env python3
"""Build the man pages and the missing completion scripts of a shell tool
from its source, without ever running it.

    scripts/gen-docs.py [--check | --options] [PROG ...]

PROG defaults to every tool with a man/PROG.1.in in the repository.

For each PROG it reads, and only reads:

    PROG                   the dispatcher: its option case arms and the
                           usage heredoc, or for a tool with no
                           subcommands its ${1:?usage: ...} line
    libexec/PROG/*.sh      one subcommand per file: its help text
                           (cmd_help "..." or a heredoc with a Usage:
                           section), its option case arms, and whether it
                           only sources another module (an alias)
    libexec/PROG/help.sh   the overview, when there is one
    lib/*.sh               the option case arms of a function a module
                           calls with "$@"

and writes man/PROG.1 from the hand-written man/PROG.1.in, whose comment
lines `.\\" @generated synopsis', `options' and `commands' it fills in;
a block between `.\\" @prose CMD' and `.\\" @end' goes under subcommand
CMD.  It writes a completion script only for a shell the repository has
none for (a file it wrote itself carries the note below and is rewritten),
and prints every disagreement between a hand-written completion, the help
text and the option parsing.  --check prints the disagreements and writes
nothing.  --options prints, and writes nothing, one line per subcommand:
its name, a tab, then every option spelling it parses as NAME:flag or
NAME:value (-h and --help left out); tests/ builds its runs from it.
"""
from __future__ import annotations

import re
import shlex
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Every tool of this repository: one hand-written man/PROG.1.in each.
PROGS: list[str] = sorted(p.name[:-len(".1.in")] for p in (ROOT / "man").glob("*.1.in"))
NOTE = "Generated by scripts/gen-docs.py from the source; do not edit."
COLOUR = re.compile(r"\$\{(?:CYAN|RESET|YELLOW|GREEN|RED|BLUE|BOLD|DIM|B|R)\}")
OPT = r"-{1,2}[A-Za-z0-9][\w-]*"


# ---------------------------------------------------------------------------
# reading shell source

@dataclass
class Opt:
    names: list[str]
    value: bool = False          # takes an argument
    eq: bool = False             # spelled --name=VALUE
    metavar: str = ""
    desc: str = ""


def heredocs(text: str) -> list[str]:
    out = []
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        m = re.search(r"<<(-?)\s*['\"]?(\w+)['\"]?", lines[i])
        if m and not lines[i].lstrip().startswith("#"):
            end, body = m.group(2), []
            i += 1
            while i < len(lines) and (lines[i].strip() if m.group(1) else lines[i]) != end:
                body.append(lines[i])
                i += 1
            out.append("\n".join(body))
        i += 1
    return out


def cmd_help_text(text: str) -> str | None:
    m = re.search(r'^\s*cmd_help\s+"', text, re.M)
    if not m:
        return None
    i, out = m.end(), []
    while i < len(text):
        c = text[i]
        if c == "\\" and i + 1 < len(text):
            out.append(text[i:i + 2])
            i += 2
            continue
        if c == '"':
            break
        out.append(c)
        i += 1
    return "".join(out)


def clean(text: str) -> str:
    """Help text as the user sees it: no colour variables, and the
    backslash escapes of a double-quoted string or heredoc undone."""
    return re.sub(r'\\([$`"\\])', r"\1", COLOUR.sub("", text)).replace("%%", "%")


def help_of(text: str) -> str | None:
    """A module's own help: its cmd_help string, else its first heredoc
    that has a Usage: section."""
    h = cmd_help_text(text)
    if h is not None:
        return clean(h)
    for doc in heredocs(text):
        doc = clean(doc)
        if re.search(r"^\s*Usage:\s*$", doc, re.M | re.I):
            return doc
    return None


ARM = re.compile(r"^\s*\(?\s*((?:%s)(?:=\*)?(?:\s*\|\s*[\w=*-]+)*)\s*\)(.*)$" % OPT)
CMP = re.compile(r"\[\[?\s*\"?\$\{?(?:1|arg|args\[[^]]*\])[^\]\"]*\"?\s*==?\s*\"?(%s)(=\*)?\"?\s*\]" % OPT)
TAKES = re.compile(r"\$\{?2\b|shift 2|i\s*\+\s*2|i\s*\+\s*1\)\)\]|CONSUMED=2|shift\s*\n\s*if \[ \$# -gt 0 \]")


def arms(text: str) -> list[Opt]:
    """Options the code tests for: case arms that begin with a dash, and
    [ "$1" = "--x" ] style comparisons."""
    out: list[Opt] = []
    lines = text.split("\n")
    for i, ln in enumerate(lines):
        if ln.lstrip().startswith("#"):
            continue
        m = ARM.match(ln)
        if m:
            body, j = m.group(2), i
            while ";;" not in body and j + 1 < len(lines):
                j += 1
                body += "\n" + lines[j]
            pats = [p.strip() for p in m.group(1).split("|") if re.fullmatch(r"%s(=\*)?" % OPT, p.strip())]
            names = [p.removesuffix("=*") for p in pats]
            eq = any(p.endswith("=*") for p in pats)
            value = eq or bool(TAKES.search(body))
            # one arm, several modes (PRUNE_MODE="${1#--}"): not aliases
            groups = [[n] for n in names] if re.search(r"\$\{1#-", body) else [names]
            out += [Opt(names=g, eq=eq, value=value) for g in groups]
        for c in CMP.finditer(ln):
            out.append(Opt(names=[c.group(1)], eq=bool(c.group(2)), value=bool(c.group(2))))
    return out


def functions(text: str) -> dict[str, str]:
    out, name, body = {}, None, []
    for ln in text.split("\n"):
        m = re.match(r"^(\w+)\s*\(\)\s*\{", ln)
        if m:
            name, body = m.group(1), [ln]
            if ln.rstrip().endswith("}") and ln.count("{") == ln.count("}"):
                out[name], name = ln, None
            continue
        if name is not None:
            body.append(ln)
            if ln.startswith("}"):
                out[name], name = "\n".join(body), None
    return out


def merge(opts: list[Opt]) -> list[Opt]:
    """One Opt per option, aliases and --x/--x=* spellings folded."""
    out: list[Opt] = []
    for o in opts:
        hit = next((x for x in out if set(x.names) & set(o.names)), None)
        if hit is None:
            out.append(Opt(list(dict.fromkeys(o.names)), o.value, o.eq, o.metavar, o.desc))
            continue
        hit.names = list(dict.fromkeys(hit.names + o.names))
        hit.value |= o.value
        hit.eq &= o.eq
        hit.metavar = hit.metavar or o.metavar
        hit.desc = hit.desc or o.desc
    return out


