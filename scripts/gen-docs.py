# a tool

@dataclass
class Command:
    name: str
    help: str | None = None              # its own help text
    overview: list[str] = field(default_factory=list)   # entry lines from the overview
    opts: list[Opt] = field(default_factory=list)       # what the code parses
    alias: tuple[str, list[str]] | None = None
    summary: str = ""


class Tool:
    def __init__(self, prog: str) -> None:
        self.prog = prog
        self.main = (ROOT / prog).read_text(encoding="utf-8")
        self.libexec = ROOT / "libexec" / prog
        self.lib: dict[str, str] = {}
        for f in sorted((ROOT / "lib").glob("*.sh")) if (ROOT / "lib").is_dir() else []:
            self.lib.update(functions(f.read_text(encoding="utf-8")))
        self.global_opts = merge(arms(self.main))
        self.overview = self._overview()
        self.commands = self._commands() if self.libexec.is_dir() else []
        self._describe_globals()

    # the usage heredoc of the dispatcher, or libexec/PROG/help.sh
    def _overview(self) -> str:
        help_sh = self.libexec / "help.sh"
        for text in ([help_sh.read_text(encoding="utf-8")] if help_sh.exists() else []) + [self.main]:
            docs = heredocs(text)
            if docs:
                return clean(docs[0])
        return ""

    def module_text(self, name: str) -> str:
        return (self.libexec / f"{name}.sh").read_text(encoding="utf-8")

    def _module_opts(self, text: str, seen: set[str] | None = None) -> list[Opt]:
        """The options TEXT parses, and those of every lib function it
        hands its arguments to ("$@" or "$1"), transitively."""
        seen = set() if seen is None else seen
        opts = arms(text)
        for fn, body in self.lib.items():
            if fn not in seen and re.search(r"^(?!\s*#).*\b%s\b[^\n]*\"\$[@1]\"" % re.escape(fn),
                                             text, re.M):
                seen.add(fn)
                opts += self._module_opts(body, seen)
        return opts

    def _alias(self, text: str) -> tuple[str, list[str]] | None:
        code = [ln.strip() for ln in text.split("\n") if ln.strip() and not ln.strip().startswith("#")]
        if len(code) == 1:
            m = re.match(r'^(?:source|\.)\s+"[^"]*/libexec/%s/([\w-]+)\.sh"\s*(.*?)\s*"\$@"$'
                         % re.escape(self.prog), code[0])
            if m:
                return m.group(1), shlex.split(m.group(2))
        return None

    def _commands(self) -> list[Command]:
        names = [p.stem for p in sorted(self.libexec.glob("*.sh"))]
        cmds = {n: Command(n) for n in names}
        for c in cmds.values():
            text = self.module_text(c.name)
            c.alias = self._alias(text)
            c.help = None if c.alias else help_of(text)
            c.opts = self._module_opts(text)
        # an overview entry: a line at its section's indent naming a command
        order: list[str] = []
        for _, lines in sections(self.overview)[1]:
            body = [ln for ln in lines if ln.strip()]
            if not body:
                continue
            base = min(indent(ln) for ln in body)
            cur: Command | None = None
            for ln in body:
                word = ln.strip().split()[0]
                if indent(ln) == base:
                    cur = cmds.get(word)
                    if cur is not None:
                        cur.overview.append(ln.strip())
                        order.append(word)
                elif cur is not None:
                    cur.overview.append(ln.rstrip())
        # nodes.sh only sources info.sh, whose help calls itself `nodes':
        # the help belongs to nodes, and info becomes the alias
        for c in list(cmds.values()):
            if c.alias and not c.alias[1]:
                t = cmds[c.alias[0]]
                if t.help and self.display(t.name, cmds) == f"{self.prog} {c.name}":
                    c.help, c.alias, t.help, t.alias = t.help, None, None, (c.name, [])
                    c.opts, t.opts = t.opts, c.opts
        # an alias inherits its target's options
        for c in cmds.values():
            if c.alias:
                target = cmds[c.alias[0]]
                injected = set(c.alias[1])
                c.opts = [o for o in target.opts if not set(o.names) & injected] + c.opts
        for c in cmds.values():
            c.opts = merge(c.opts)
            c.summary = self._summary(c, cmds)
        seq = list(dict.fromkeys(order + names))
        return [cmds[n] for n in seq]

    def _summary(self, c: Command, cmds: dict[str, Command]) -> str:
        if c.alias:
            t = c.alias[0]
            target = self.display(t, cmds) if cmds[t].help else f"{self.prog} {t}"
            if cmds[t].alias:
                target = f"{self.prog} {cmds[t].alias[0]}"
            args = " ".join(c.alias[1])
            return f"Same as `{target}{' ' + args if args else ''}'; see {target.split()[-1]}."
        if c.help:
            first = next((ln.strip() for ln in c.help.split("\n") if ln.strip()), "")
            m = re.search(r"\s[\u2014-]+\s+(.*)$", first)
            if m:
                return m.group(1).strip()
        if c.overview:
            tag, desc = split2(c.overview[0])
            if desc:
                return desc
            for ln in c.overview[1:]:
                if ln.strip() and not ln.strip().startswith("-"):
                    return ln.strip()
        # the module's own header comment: `# name -- what it does'
        m = re.search(r"^#\s*%s\s+[\u2014-]+\s+(.+)$" % re.escape(c.name),
                      self.module_text(c.name), re.M)
        return m.group(1).strip() if m else ""

    def display(self, name: str, cmds: dict[str, Command]) -> str:
        """The name the help text uses for a module: info.sh calls itself
        `nodes' when nodes.sh is its alias."""
        c = cmds[name]
        if c.help:
            first = next((ln for ln in c.help.split("\n") if ln.strip()), "")
            m = re.match(r"\s*%s\s+([\w-]+)" % re.escape(self.prog), first)
            if m and m.group(1) != name and m.group(1) in cmds:
                return f"{self.prog} {m.group(1)}"
        return f"{self.prog} {name}"

    def _describe_globals(self) -> None:
        """Descriptions for the dispatcher's own options, from the
        overview's Global/Common sections."""
        found = self.global_help()
        for o in self.global_opts:
            for h in found:
                if set(h.names) & set(o.names):
                    o.desc, o.metavar = h.desc, h.metavar
                    o.value = o.value or h.value
                    o.names = list(dict.fromkeys(h.names + o.names))

    def global_help(self) -> list[Opt]:
        out = []
        for head, lines in sections(self.overview)[1]:
            if re.search(r"global|common", head, re.I):
                out += [o for e in entries(lines) for o in entry_opts(e)]
        return out

    # options a command's help documents
    def help_opts(self, c: Command) -> list[Opt]:
        out: list[Opt] = []
        if c.help:
            for head, lines in sections(c.help)[1]:
                if head.lower().startswith("option"):
                    out += [o for e in entries(lines) for o in entry_opts(e)]
            return merge(out)
        for ln in c.overview[1:]:
            s = ln.strip()
            if s.startswith("-"):
                out += entry_opts(Entry(*split2(s)))
        return merge(out)

    def accepted(self, c: Command) -> set[str]:
        return {n for o in c.opts + self.global_opts for n in o.names}


